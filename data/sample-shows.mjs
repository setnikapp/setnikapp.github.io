function upcomingFridayOffset(todayYmd) {
  const dow = dayOfWeek(todayYmd); // 0=Sun..6=Sat
  if (dow === 5) return 0; // Fri
  if (dow === 6) return 0; // Sat (today is already weekend)
  if (dow === 0) return 0; // Sun
  return 5 - dow; // Mon->4, Tue->3, Wed->2, Thu->1
}

